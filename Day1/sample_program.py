# simple program to ask two numbers from the user and find their sum, differnce, product and quotient.

num1 = int(input("Enter the first number :"))
num2 = int(input("Enter the second number :"))

sum = num1 + num2
difference = num1 - num2
product = num1 * num2
quotient = num1 / num2


print(f"The sum of two number is : {sum}")
print(f"The difference of two number is : {difference}")
print(f"The product of two number is : {product}")
print(f"The quotinet of two number is : {quotient}")